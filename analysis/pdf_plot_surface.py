"""Typed plotting boundary for Matplotlib's extensible keyword interfaces."""

from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Literal, Protocol

from matplotlib.axis import Tick
from matplotlib.container import BarContainer
from matplotlib.legend import Legend
from matplotlib.lines import Line2D
from matplotlib.spines import Spine
from matplotlib.table import Table
from matplotlib.text import Text


class PdfAxes(Protocol):
    @property
    def spines(self) -> Mapping[str, Spine]: ...

    def bar(self, x: Sequence[int], height: Sequence[float], *, color: str, width: float) -> BarContainer: ...
    def plot(self, x: Sequence[int], y: Sequence[float], *, color: str, marker: str = "",
             linewidth: float, markersize: float = 4.5, linestyle: str = "-") -> list[Line2D]: ...
    def axhline(self, y: float, *, color: str, linewidth: float, linestyle: str) -> Line2D: ...
    def set_ylim(self, bottom: float, top: float) -> tuple[float, float]: ...
    def set_xlim(self, left: float, right: float) -> tuple[float, float]: ...
    def text(self, x: float, y: float, s: str, *, ha: str, va: str, fontsize: float) -> Text: ...
    def set_title(self, label: str, *, fontsize: float, loc: Literal["left", "center", "right"], pad: float) -> Text: ...
    def set_xticks(self, ticks: Sequence[int], labels: Sequence[str], *, fontsize: float) -> list[Tick]: ...
    def tick_params(self, *, axis: Literal["x", "y", "both"], labelsize: float) -> None: ...
    def set_xlabel(self, xlabel: str, *, fontsize: float) -> Text: ...
    def grid(self, *, axis: Literal["x", "y", "both"], alpha: float) -> None: ...
    def set_axis_off(self) -> None: ...
    def table(self, *, cellText: Sequence[Sequence[str]], colLabels: Sequence[str],
              loc: str, cellLoc: Literal["left", "center", "right"]) -> Table: ...


class PdfFigure(Protocol):
    def text(self, x: float, y: float, s: str, *, fontsize: float, weight: str = "normal",
             color: str = "black", ha: str = "left", va: str = "baseline",
             linespacing: float = 1.2) -> Text: ...
    def legend(self, *, handles: Sequence[Line2D], loc: Literal["upper left"], bbox_to_anchor: tuple[float, float],
               ncols: int, frameon: bool, fontsize: float) -> Legend: ...
    def add_subplot(self, nrows: int, ncols: int, index: int) -> PdfAxes: ...
    def add_axes(self, rect: tuple[float, float, float, float]) -> PdfAxes: ...
    def subplots_adjust(self, *, left: float, right: float, bottom: float, top: float,
                        hspace: float, wspace: float) -> None: ...
    def savefig(self, fname: Path, *, dpi: int) -> None: ...
    def clear(self) -> None: ...


class PdfSink(Protocol):
    def savefig(self, figure: PdfFigure) -> None: ...


def figure_surface(figure: PdfFigure) -> PdfFigure:
    """Keep precisely the actual plotting contract, without casts or ignores."""
    return figure


def pdf_sink(sink: PdfSink) -> PdfSink:
    """The save operation consumes real figures rather than pre-rendered screenshots."""
    return sink
